import { access, writeFile } from 'node:fs/promises'
import path from 'node:path'
import {
  families,
  type GalleryFamily,
  type GalleryShot,
  type GalleryTheme,
  themesOf,
} from './manifest'
import { GALLERY_DIR, shotRelativePath } from './paths'

/**
 * Writes docs/gallery/README.md from the manifest: a table of contents, then a section per family
 * with its description, its guide and a two-column grid of thumbnails. A shot whose PNG is missing
 * gets a "not captured yet" cell instead of a broken image, so a partial `GALLERY_ONLY` run still
 * leaves a complete index.
 */

const THUMB_WIDTH = 420

/** GitHub's heading anchor: lowercase, punctuation dropped, spaces to hyphens. */
export function anchor(title: string) {
  return title
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
}

function escapeHtml(text: string) {
  return text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
}

async function exists(file: string) {
  try {
    await access(file)
    return true
  } catch {
    return false
  }
}

async function cell(family: GalleryFamily, shot: GalleryShot, theme: GalleryTheme) {
  const relative = shotRelativePath(family, shot, theme)
  const title = theme === 'dark' ? `${shot.title} (dark)` : shot.title
  const caption = [
    `<strong>${escapeHtml(title)}</strong> · <code>${escapeHtml(shot.route)}</code>`,
    shot.note ? `<br><em>${escapeHtml(shot.note)}</em>` : '',
  ].join('')
  if (!(await exists(path.join(GALLERY_DIR, relative)))) {
    return (
      `<td width="50%" valign="top"><em>Not captured yet:</em> ` +
      `<code>GALLERY_ONLY=${family.id}/${shot.id} pnpm gallery</code><br>${caption}</td>`
    )
  }
  return (
    `<td width="50%" valign="top"><a href="${relative}"><img src="${relative}" width="${THUMB_WIDTH}" ` +
    `alt="${escapeHtml(title)}"></a><br>${caption}</td>`
  )
}

async function familySection(family: GalleryFamily) {
  const cells: string[] = []
  for (const shot of family.shots) {
    for (const theme of themesOf(shot)) cells.push(await cell(family, shot, theme))
  }
  const rows: string[] = []
  for (let index = 0; index < cells.length; index += 2) {
    rows.push(`<tr>\n${cells.slice(index, index + 2).join('\n')}\n</tr>`)
  }
  return [
    `## ${family.title}`,
    '',
    `${family.description} Guide: [${linkTitle(family)}](${family.guide}).`,
    '',
    '<table>',
    ...rows,
    '</table>',
    '',
  ].join('\n')
}

function linkTitle(family: GalleryFamily) {
  return family.guide.startsWith('../../README.md') ? 'README' : family.title
}

function shotCount(family: GalleryFamily) {
  return family.shots.reduce((count, shot) => count + themesOf(shot).length, 0)
}

export async function writeIndex() {
  const toc = [
    '| Family | Screenshots | Guide |',
    '| --- | --- | --- |',
    ...families.map(
      (family) =>
        `| [${family.title}](#${anchor(family.title)}) | ${shotCount(family)} | [${linkTitle(family)}](${family.guide}) |`,
    ),
  ].join('\n')

  const sections: string[] = []
  for (const family of families) sections.push(await familySection(family))

  const content = [
    '<!-- Generated by `pnpm gallery` from apps/preview/gallery/manifest.ts. Edit the manifest, not this file. -->',
    '',
    '# Gallery',
    '',
    'Screenshots of every page the preview renders, one family per guide: the full page at a 1440×900',
    'viewport in the light host theme and, beside it, the same page in the dark theme. The auth and',
    'status pages force dark mode, so they appear once. Click a thumbnail for the full-size PNG.',
    '',
    'To add a page or component, add it to `apps/preview/gallery/manifest.ts` and run `pnpm gallery`',
    '(`GALLERY_ONLY=<family>` captures one family and still rewrites this index); see',
    '[Development](../development.md#screenshot-gallery).',
    '',
    toc,
    '',
    ...sections,
  ].join('\n')

  await writeFile(path.join(GALLERY_DIR, 'README.md'), content)
}

export default writeIndex
